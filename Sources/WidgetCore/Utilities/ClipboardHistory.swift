import AppKit
import Observation

public nonisolated struct ClipboardItem: Identifiable, Hashable, Sendable {
    public enum Content: Hashable, Sendable {
        case text(String)
        case image(Data)
        case files([URL])
    }

    public var id: UUID
    public var content: Content
    public var copiedAt: Date
    public var sourceBundleID: String?
    public var isPinned: Bool

    public init(id: UUID = UUID(), content: Content, copiedAt: Date = Date(), sourceBundleID: String? = nil, isPinned: Bool = false) {
        self.id = id
        self.content = content
        self.copiedAt = copiedAt
        self.sourceBundleID = sourceBundleID
        self.isPinned = isPinned
    }

    public var preview: String {
        switch content {
        case let .text(text): text.trimmingCharacters(in: .whitespacesAndNewlines).replacingOccurrences(of: "\n", with: " ")
        case .image: ""
        case let .files(urls): urls.map(\.lastPathComponent).joined(separator: ", ")
        }
    }
}

public nonisolated enum ClipboardPolicy {
    /// Pasteboard types that password managers and other apps use to say "do not record".
    /// See nspasteboard.org.
    public static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    public static let maxItems = 40
    public static let maxTextLength = 20_000
    public static let maxImageBytes = 6_000_000

    public static func shouldIgnore(types: [String]) -> Bool {
        types.contains { ignoredTypes.contains($0) }
    }

    /// Adds `item` on top, removing an older identical entry and trimming unpinned history.
    public static func inserting(_ item: ClipboardItem, into items: [ClipboardItem]) -> [ClipboardItem] {
        var result = items
        var item = item
        if let existing = result.firstIndex(where: { $0.content == item.content }) {
            item.isPinned = result[existing].isPinned
            result.remove(at: existing)
        }
        result.insert(item, at: 0)
        var unpinned = 0
        return result.filter { entry in
            if entry.isPinned { return true }
            unpinned += 1
            return unpinned <= maxItems
        }
    }
}

/// Clipboard history. Reads the pasteboard only when its change counter moves (checked
/// every 0.75 s while the widget is in the dock; reading an integer is the only API macOS
/// offers). History lives in memory; only pinned text survives a restart (the app decides).
///
/// Since macOS 15.4, reading the general pasteboard without a paste gesture shows an alert
/// unless the user chose "Always Allow" for PulseDock (System Settings › Privacy & Security ›
/// Paste from Other Apps). PulseDock therefore records only with that permission; it never
/// reads in the background just to make the alert appear.
@Observable
public final class ClipboardHistory {
    public enum Access: Sendable, Equatable {
        /// Recording is possible without alerts (Always Allow, or macOS before 15.4).
        case allowed
        /// macOS would ask on every read; PulseDock waits for the user.
        case needsPermission
        /// The user chose Always Deny.
        case denied
    }

    public private(set) var items: [ClipboardItem] = []
    public private(set) var access: Access = ClipboardHistory.currentAccess()
    public var isPaused = false
    public var isEnabled = false {
        didSet { if isEnabled != oldValue { reschedule() } }
    }
    @ObservationIgnored public var onPinnedChange: ([String]) -> Void = { _ in }

    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount
    /// Change count produced by our own "copy again", which must not create a new entry.
    @ObservationIgnored private var ownChangeCount: Int?

    public init() {}

    public func restorePinned(_ texts: [String]) {
        let pinned = texts.map { ClipboardItem(content: .text($0), copiedAt: .distantPast, isPinned: true) }
        items = pinned + items.filter { !$0.isPinned }
    }

    private func reschedule() {
        timer?.invalidate()
        timer = nil
        guard isEnabled else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.75, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.25
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    public static func currentAccess() -> Access {
        if #available(macOS 15.4, *) {
            switch NSPasteboard.general.accessBehavior {
            case .alwaysAllow: return .allowed
            case .alwaysDeny: return .denied
            default: return .needsPermission
            }
        }
        return .allowed
    }

    /// The user asked to start recording: one read, which makes macOS show its permission
    /// alert once and list PulseDock in System Settings, where "Always Allow" can be chosen.
    public func requestAccess() {
        _ = NSPasteboard.general.string(forType: .string)
        access = Self.currentAccess()
        lastChangeCount = NSPasteboard.general.changeCount
    }

    public func refreshAccess() {
        access = Self.currentAccess()
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        access = Self.currentAccess()
        guard access == .allowed, !isPaused, count != ownChangeCount else { return }
        let types = pasteboard.types?.map(\.rawValue) ?? []
        guard !ClipboardPolicy.shouldIgnore(types: types) else { return }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        let content: ClipboardItem.Content
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            content = .files(urls)
        } else if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            content = .text(String(text.prefix(ClipboardPolicy.maxTextLength)))
        } else if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff), data.count <= ClipboardPolicy.maxImageBytes {
            content = .image(data)
        } else {
            return
        }
        items = ClipboardPolicy.inserting(ClipboardItem(content: content, sourceBundleID: source), into: items)
    }

    /// Puts an entry back on the pasteboard.
    public func copy(_ item: ClipboardItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.content {
        case let .text(text): pasteboard.setString(text, forType: .string)
        case let .image(data): pasteboard.setData(data, forType: data.starts(with: [0x89, 0x50]) ? .png : .tiff)
        case let .files(urls): pasteboard.writeObjects(urls as [NSURL])
        }
        ownChangeCount = pasteboard.changeCount
        lastChangeCount = pasteboard.changeCount
        items = ClipboardPolicy.inserting(ClipboardItem(id: item.id, content: item.content, sourceBundleID: item.sourceBundleID, isPinned: item.isPinned), into: items)
    }

    public func togglePin(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
        publishPinned()
    }

    public func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        publishPinned()
    }

    public func clearUnpinned() {
        items.removeAll { !$0.isPinned }
    }

    private func publishPinned() {
        onPinnedChange(items.filter(\.isPinned).compactMap { item in
            if case let .text(text) = item.content { return text }
            return nil
        })
    }
}
