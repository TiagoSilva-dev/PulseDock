#!/usr/bin/env python3
"""Generates Localizable.strings and Localizable.stringsdict for every supported language.

English values come from the `tr("key", "English")` and `trp("key", one: "…", other: "…")`
calls in the Swift sources, so the code is the single source of truth for keys. Translations
live in Resources/Localization/<lang>.json; plural keys map to {"one": "…", "other": "…"}
(plus any other CLDR category the language needs, such as "many").

Usage: scripts/localize.py [--strict]   (--strict fails when a translation is missing)
"""
import json
import pathlib
import plistlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = ROOT / "Sources" / "PulseDockApp"
TRANSLATIONS = ROOT / "Resources" / "Localization"
OUTPUT = ROOT / "Resources" / "Generated"
LANGUAGES = ["pt-BR"]

CALL = re.compile(r'\btr\(\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"')
PLURAL = re.compile(r'\btrp\(\s*"((?:[^"\\]|\\.)*)"\s*,\s*one:\s*"((?:[^"\\]|\\.)*)"\s*,\s*other:\s*"((?:[^"\\]|\\.)*)"')
PLACEHOLDER = re.compile(r"%(?:\d+\$)?l?[@dsf]")


def unescape(text: str) -> str:
    return bytes(text, "utf-8").decode("unicode_escape").encode("latin-1").decode("utf-8")


def strings_literal(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def collect() -> tuple:
    keys, plurals = {}, {}
    for path in sorted(SOURCES.rglob("*.swift")):
        source = path.read_text(encoding="utf-8")
        for key, english in CALL.findall(source):
            value = unescape(english)
            if key in keys and keys[key] != value:
                print(f"warning: key {key} has two English values: {keys[key]!r} / {value!r}", file=sys.stderr)
            keys.setdefault(key, value)
        for key, one, other in PLURAL.findall(source):
            plurals.setdefault(key, {"one": unescape(one), "other": unescape(other)})
    return keys, plurals


def write_info_plist(language: str, values: dict) -> None:
    known = plistlib.loads((ROOT / "Resources" / "Info.plist").read_bytes()) if values else {}
    for key in values:
        if key not in known:
            raise SystemExit(f"{language}: InfoPlist.{key} is not a key of Resources/Info.plist")
    directory = OUTPUT / f"{language}.lproj"
    directory.mkdir(parents=True, exist_ok=True)
    target = directory / "InfoPlist.strings"
    if not values:
        target.unlink(missing_ok=True)
        return
    lines = ["/* Generated by scripts/localize.py — do not edit. */"]
    lines += [f'"{strings_literal(k)}" = "{strings_literal(v)}";' for k, v in sorted(values.items())]
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_plurals(language: str, values: dict) -> None:
    directory = OUTPUT / f"{language}.lproj"
    directory.mkdir(parents=True, exist_ok=True)
    document = {}
    for key in sorted(values):
        forms = dict(values[key])
        forms.update({"NSStringFormatSpecTypeKey": "NSStringPluralRuleType", "NSStringFormatValueTypeKey": "ld"})
        document[key] = {"NSStringLocalizedFormatKey": "%#@count@", "count": forms}
    with open(directory / "Localizable.stringsdict", "wb") as handle:
        plistlib.dump(document, handle, sort_keys=True)


def write(language: str, values: dict) -> None:
    directory = OUTPUT / f"{language}.lproj"
    directory.mkdir(parents=True, exist_ok=True)
    lines = ["/* Generated by scripts/localize.py — do not edit. */"]
    for key in sorted(values):
        lines.append(f'"{strings_literal(key)}" = "{strings_literal(values[key])}";')
    (directory / "Localizable.strings").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    strict = "--strict" in sys.argv
    english, english_plurals = collect()
    write("en", english)
    write_plurals("en", english_plurals)
    failed = False
    for language in LANGUAGES:
        path = TRANSLATIONS / f"{language}.json"
        translations = json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}
        # "InfoPlist.<Key>" entries localize user-facing Info.plist strings (permission prompts).
        info_plist = {k[len("InfoPlist."):]: v for k, v in translations.items() if k.startswith("InfoPlist.")}
        translations = {k: v for k, v in translations.items() if not k.startswith("InfoPlist.")}
        write_info_plist(language, info_plist)
        flat = {k: v for k, v in translations.items() if isinstance(v, str)}
        plural = {k: v for k, v in translations.items() if isinstance(v, dict)}
        missing = sorted(set(english) - set(flat)) + sorted(set(english_plurals) - set(plural))
        unused = sorted((set(flat) - set(english)) | (set(plural) - set(english_plurals)))
        write(language, {key: flat.get(key, value) for key, value in english.items()})
        write_plurals(language, {key: plural.get(key, forms) for key, forms in english_plurals.items()})
        if missing:
            print(f"{language}: {len(missing)} missing translations", file=sys.stderr)
            for key in missing[:40]:
                print(f"  {key}: {english.get(key) or english_plurals.get(key)}", file=sys.stderr)
            failed = failed or strict
        if unused:
            print(f"{language}: {len(unused)} unused keys (ignored): {', '.join(unused[:10])}", file=sys.stderr)
        # Placeholders must match, or String(format:) would crash at runtime.
        for key, value in flat.items():
            if key in english and PLACEHOLDER.findall(value) != PLACEHOLDER.findall(english[key]):
                print(f"{language}: placeholder mismatch in {key}", file=sys.stderr)
                failed = True
        for key, forms in plural.items():
            if key in english_plurals and ("other" not in forms or any(PLACEHOLDER.findall(f) != ["%ld"] for f in forms.values())):
                print(f"{language}: plural forms of {key} need 'other' and exactly one %ld each", file=sys.stderr)
                failed = True
    print(f"{len(english)} keys, {len(english_plurals)} plural keys")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
